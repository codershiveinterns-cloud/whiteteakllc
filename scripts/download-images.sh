download_set() {
  local category=$1
  local fallback=$2
  shift 2
  local ids=("$@")
  local i=1
  for id in "${ids[@]}"; do
    local n=$(printf "%02d" $i)
    local dest="$BASE/$category/$category-$n.jpg"
    local url="${UNSPLASH}${id}${SUFFIX}"
    curl -sS -L --max-time 20 -o "$dest" "$url"
    # if size < 2000 bytes, treat as failure and use fallback
    local sz=$(wc -c <"$dest" 2>/dev/null || echo 0)
    if [ "$sz" -lt 2000 ]; then
      echo "FALLBACK $category-$n (id=$id size=$sz)"
      curl -sS -L --max-time 20 -o "$dest" "${UNSPLASH}${fallback}${SUFFIX}"
    fi
    i=$((i+1))
  done
}

